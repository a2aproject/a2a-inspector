// Generates TypeScript types for A2A payloads from the JSON Schemas the
// backend validates with (internal/validate/schemas): v1.0, generated from
// a2a.proto, and the v0.3 specification's JSON-RPC schema.
// Run with `npm run gen:types` after scripts/gen-schemas.sh.
import { readFileSync, writeFileSync } from 'node:fs';
import { compile } from 'json-schema-to-typescript';

const schemas = new URL('../../internal/validate/schemas/', import.meta.url);
const out = new URL('../src/a2a/', import.meta.url);
const options = {
  unreachableDefinitions: true,
  additionalProperties: false,
  format: true,
  style: { singleQuote: true, printWidth: 120 },
};

// Well-known proto types, as ProtoJSON writes them.
const wellKnown = {
  'google.protobuf.Struct': { type: 'object', additionalProperties: true },
  'google.protobuf.Value': { tsType: 'unknown' },
  'google.protobuf.Timestamp': { type: 'string', description: 'RFC 3339 timestamp.' },
};

function v10() {
  const doc = JSON.parse(readFileSync(new URL('a2a-v1.0.json', schemas), 'utf8'));
  const short = (name) => name.replace(/^lf\.a2a\.v1\./, '');
  const rewrite = (node) => {
    if (Array.isArray(node)) return node.map(rewrite);
    if (node === null || typeof node !== 'object') return node;
    if (typeof node.$ref === 'string') {
      const name = node.$ref.replace('#/$defs/', '');
      if (wellKnown[name]) return { ...wellKnown[name], description: node.description };
      // A description next to a $ref would make the generator emit a copy of the type.
      return { $ref: `#/definitions/${short(name)}` };
    }
    const copy = {};
    for (const [k, v] of Object.entries(node)) {
      // The snake_case aliases protojson also accepts aren't part of the shape agents send.
      if (k === 'patternProperties') continue;
      copy[k] = rewrite(v);
    }
    return copy;
  };
  const definitions = {};
  for (const [name, def] of Object.entries(doc.$defs)) {
    if (wellKnown[name]) continue;
    definitions[short(name)] = { ...rewrite(def), title: short(name) };
  }
  return { title: 'A2A v1.0', type: 'object', definitions };
}

function v03() {
  const doc = JSON.parse(readFileSync(new URL('a2a-v0.3.json', schemas), 'utf8'));
  const definitions = {};
  const rewrite = (node) => {
    if (Array.isArray(node)) return node.map(rewrite);
    if (node === null || typeof node !== 'object') return node;
    if (typeof node.$ref === 'string') return { $ref: node.$ref };
    return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, rewrite(v)]));
  };
  for (const [name, def] of Object.entries(doc.definitions)) {
    definitions[name] = { ...rewrite(def), title: name };
  }
  return { title: 'A2A v0.3', type: 'object', definitions };
}

for (const [file, schema, source] of [
  ['v1.gen.ts', v10(), 'internal/validate/schemas/a2a-v1.0.json (from a2a.proto, A2A v1.0.1)'],
  ['v03.gen.ts', v03(), 'internal/validate/schemas/a2a-v0.3.json (the A2A v0.3.0 JSON-RPC schema)'],
]) {
  const banner = `/* Generated by ui/scripts/gen-types.mjs from ${source}. Don't edit. */`;
  const ts = await compile(schema, schema.title, { ...options, bannerComment: banner });
  writeFileSync(new URL(file, out), ts);
}
