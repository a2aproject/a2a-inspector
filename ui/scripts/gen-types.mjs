// Generates TypeScript types for A2A payloads from the JSON Schemas the
// backend validates with (internal/validate/schemas): v1.0, generated from
// a2a.proto, and the v0.3 specification's JSON-RPC schema.
// Run with `npm run gen:types` after scripts/gen-schemas.sh.
import { readFileSync, writeFileSync } from 'node:fs';
import { compile } from 'json-schema-to-typescript';

const schemas = new URL('../../internal/validate/schemas/', import.meta.url);
const out = new URL('../src/a2a/', import.meta.url);
const options = {
  unreachableDefinitions: true,
  additionalProperties: false,
  format: true,
  style: { singleQuote: true, printWidth: 120 },
};

// Well-known proto types, as ProtoJSON writes them.
const wellKnown = {
  'google.protobuf.Struct': { type: 'object', additionalProperties: true },
  'google.protobuf.Value': { tsType: 'unknown' },
  'google.protobuf.Timestamp': { type: 'string', description: 'RFC 3339 timestamp.' },
};

function v10() {
  const doc = JSON.parse(readFileSync(new URL('a2a-v1.0.json', schemas), 'utf8'));
  const short = (name) => name.replace(/^lf\.a2a\.v1\./, '');
  const rewrite = (node) => {
    if (Array.isArray(node)) return node.map(rewrite);
    if (node === null || typeof node !== 'object') return node;
    if (typeof node.$ref === 'string') {
      const name = node.$ref.replace('#/$defs/', '');
      if (wellKnown[name]) return { ...wellKnown[name], description: node.description };
      // A description next to a $ref would make the generator emit a copy of the type.
      return { $ref: `#/definitions/${short(name)}` };
    }
    const copy = {};
    for (const [k, v] of Object.entries(node)) {
      // The snake_case aliases protojson also accepts aren't part of the shape agents send.
      if (k === 'patternProperties') continue;
      copy[k] = rewrite(v);
    }
    return copy;
  };
  const definitions = {};
  for (const [name, def] of Object.entries(doc.$defs)) {
    if (wellKnown[name]) continue;
    definitions[short(name)] = { ...rewrite(def), title: short(name) };
  }
  return { title: 'A2A v1.0', type: 'object', definitions };
}

function v03() {
  const doc = JSON.parse(readFileSync(new URL('a2a-v0.3.json', schemas), 'utf8'));
  const definitions = {};
  const rewrite = (node) => {
    if (Array.isArray(node)) return node.map(rewrite);
    if (node === null || typeof node !== 'object') return node;
    if (typeof node.$ref === 'string') return { $ref: node.$ref };
    return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, rewrite(v)]));
  };
  for (const [name, def] of Object.entries(doc.definitions)) {
    definitions[name] = { ...rewrite(def), title: name };
  }
  return { title: 'A2A v0.3', type: 'object', definitions };
}

for (const [file, schema, source] of [
  ['v1.gen.ts', v10(), 'internal/validate/schemas/a2a-v1.0.json (from a2a.proto, A2A v1.0.1)'],
  ['v03.gen.ts', v03(), 'internal/validate/schemas/a2a-v0.3.json (the A2A v0.3.0 JSON-RPC schema)'],
]) {
  const banner = `/* Generated by ui/scripts/gen-types.mjs from ${source}. Don't edit. */`;
  const ts = await compile(schema, schema.title, { ...options, bannerComment: banner });
  writeFileSync(new URL(file, out), ts);
}

// The card editor's schemas: the agent card of each version and the definitions it uses, for
// completions and documentation as the user types. Validation stays in the backend.

// Fields a2a.proto (v1.0.1) marks REQUIRED, which the generated v1.0 schema doesn't list.
const v10Required = {
  AgentCard: ['name', 'description', 'supportedInterfaces', 'version', 'capabilities', 'defaultInputModes', 'defaultOutputModes', 'skills'],
  AgentInterface: ['url', 'protocolBinding', 'protocolVersion'],
  AgentProvider: ['url', 'organization'],
  AgentSkill: ['id', 'name', 'description', 'tags'],
  AgentCardSignature: ['protected', 'signature'],
  APIKeySecurityScheme: ['location', 'name'],
  HTTPAuthSecurityScheme: ['scheme'],
  OAuth2SecurityScheme: ['flows'],
  OpenIdConnectSecurityScheme: ['openIdConnectUrl'],
  AuthorizationCodeOAuthFlow: ['authorizationUrl', 'tokenUrl', 'scopes'],
  ClientCredentialsOAuthFlow: ['tokenUrl', 'scopes'],
  DeviceCodeOAuthFlow: ['deviceAuthorizationUrl', 'tokenUrl', 'scopes'],
};

/** Joins the lines of a wrapped comment into paragraphs, keeping list items on their own lines. */
function prose(text) {
  const lines = text
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => !/^Next ID: \d+$/.test(l));
  let out = '';
  for (const line of lines) {
    if (!out) out = line;
    else if (!line) out += '\n\n';
    else if (out.endsWith('\n') || /^([-*]|\d+\.) /.test(line)) out += (out.endsWith('\n') ? '' : '\n') + line;
    else out += ` ${line}`;
  }
  return out.trim();
}

/** The definitions reachable from root, keyed by their short names, with $refs to "#/definitions/<name>". */
function cardSchema(defs, root, short, refName, extra = () => ({})) {
  const names = new Set();
  const visit = (name) => {
    if (names.has(name)) return;
    names.add(name);
    JSON.stringify(defs[name], (k, v) => {
      if (k === '$ref') visit(refName(v));
      return v;
    });
  };
  visit(root);
  const rewrite = (node, key) => {
    if (Array.isArray(node)) return node.map((n) => rewrite(n));
    if (node === null || typeof node !== 'object') return node;
    const copy = {};
    for (const [k, v] of Object.entries(node)) {
      // The snake_case aliases protojson also accepts would only clutter the suggestions.
      if (k === 'patternProperties' || k === 'title') continue;
      // proto3's zero defaults say nothing.
      if (k === 'default' && (v === '' || v === false || v === 0)) continue;
      if (k === '$ref') copy[k] = `#/definitions/${short(refName(v))}`;
      else if (k === 'description' && typeof v === 'string' && key !== 'properties') copy[k] = prose(v);
      else copy[k] = rewrite(v, k);
    }
    return copy;
  };
  const definitions = {};
  for (const name of [...names].sort()) {
    definitions[short(name)] = { ...rewrite(defs[name]), ...extra(short(name)) };
  }
  return { $ref: `#/definitions/${short(root)}`, definitions };
}

{
  const v10doc = JSON.parse(readFileSync(new URL('a2a-v1.0.json', schemas), 'utf8'));
  const v03doc = JSON.parse(readFileSync(new URL('a2a-v0.3.json', schemas), 'utf8'));
  const cards = {
    '1.0': cardSchema(
      v10doc.$defs,
      'lf.a2a.v1.AgentCard',
      (name) => name.replace(/^lf\.a2a\.v1\./, '').replace(/^google\.protobuf\./, ''),
      (ref) => ref.replace('#/$defs/', ''),
      (name) => (v10Required[name] ? { required: v10Required[name] } : {}),
    ),
    '0.3': cardSchema(
      v03doc.definitions,
      'AgentCard',
      (name) => name,
      (ref) => ref.replace('#/definitions/', ''),
    ),
  };
  const banner =
    "/* Generated by ui/scripts/gen-types.mjs from internal/validate/schemas: each version's agent card and the definitions it uses. Don't edit. */";
  writeFileSync(new URL('card-schemas.gen.ts', out), `${banner}\n\nexport const cardSchemas: Record<string, unknown> = ${JSON.stringify(cards, null, 2)};\n`);
}
